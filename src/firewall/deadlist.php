<?php

/**
 * Apply Persoc deadlist (block outbound connections to listed sites) using nftables.
 *
 * deadlist.csv format (CSV):
 *   first column: hostname OR IP (v4/v6)
 *   other columns optional (reason, notes...)
 *
 * Example:
 *   example.com,malware
 *   1.2.3.4,ads
 *   # comment
 *
 * Requires: nft (nftables) + permissions to run it.
 */

/**
 * Update the dnsmasq blocklist transactionally. Requires root (or a narrowly
 * privileged helper). DNS blocking is optional and controlled by
 * persoc_dns_enabled() in firewall_deadlist().
 */
function persoc_dns_apply_deadlist(string $csvPath): array
{
    if (!is_readable($csvPath))
        return ["ok" => false, "error" => "deadlist not readable: " . $csvPath];

    $raw = file($csvPath, FILE_IGNORE_NEW_LINES);
    if ($raw === false)
        return ["ok" => false, "error" => "cannot read deadlist: " . $csvPath];

    $domains = [];
    foreach ($raw as $line)
    {
        $line = trim($line);
        if ($line === "" || str_starts_with($line, "#"))
            continue;

        $cols = str_getcsv($line);
        $target = strtolower(rtrim(trim($cols[0] ?? ""), "."));
        if ($target === "" || filter_var($target, FILTER_VALIDATE_IP))
            continue;

        // Reject malformed hostnames rather than inserting arbitrary dnsmasq
        // directives; a trailing dot is normalized above.
        if (filter_var($target, FILTER_VALIDATE_DOMAIN, FILTER_FLAG_HOSTNAME))
            $domains[$target] = true;
    }
    $domains = array_keys($domains);
    sort($domains, SORT_STRING);

    $config = "# Generated by persoc\n# DO NOT EDIT MANUALLY\n\n";
    foreach ($domains as $domain)
        $config .= "address=/" . $domain . "/#\n";

    $path = "/etc/dnsmasq.d/block.conf";
    $dir = dirname($path);
    if (!is_dir($dir) || !is_writable($dir))
        return ["ok" => false, "error" => "dnsmasq directory not writable: " . $dir];

    // This lock prevents concurrent Persoc executions from racing. It is kept
    // outside dnsmasq.d to avoid being interpreted as a configuration file.
    $lock = @fopen("/run/persoc-dns.lock", "c");
    if ($lock === false || !flock($lock, LOCK_EX))
        return ["ok" => false, "error" => "cannot lock DNS update"];

    try
    {
        $previous = is_file($path) ? @file_get_contents($path) : null;
        if ($previous === false)
            return ["ok" => false, "error" => "cannot read previous dnsmasq config"];
        if ($previous === $config)
            return ["ok" => true, "domains" => count($domains), "changed" => false];

        $tmp = @tempnam($dir, ".persoc-");
        if ($tmp === false)
            return ["ok" => false, "error" => "cannot create temporary config"];

        // dnsmasq loads only *.conf in standard conf-dir configurations.
        // Use a non-.conf temporary file and then rename atomically.
        try
        {
            if (@file_put_contents($tmp, $config) !== strlen($config) ||
                !@chmod($tmp, 0644))
                return ["ok" => false, "error" => "cannot write temporary config"];

            if (!@rename($tmp, $path))
                return ["ok" => false, "error" => "cannot install dnsmasq config"];
            $tmp = null;

            exec("dnsmasq --test 2>&1", $check, $testStatus);
            if ($testStatus === 0)
            {
                exec("systemctl restart dnsmasq 2>&1", $restart, $restartStatus);
                if ($restartStatus === 0)
                    return ["ok" => true, "domains" => count($domains), "changed" => true];
                $reason = "dnsmasq restart failed: " . implode(" ", $restart);
            }
            else
                $reason = "dnsmasq config test failed: " . implode(" ", $check);

            // Roll back even when the validation or restart failed. A previous
            // file is restored atomically; otherwise remove our newly added file.
            if ($previous === null)
                $restored = @unlink($path);
            else
            {
                $rollback = @tempnam($dir, ".persoc-rollback-");
                $restored = $rollback !== false &&
                    @file_put_contents($rollback, $previous) === strlen($previous) &&
                    @chmod($rollback, 0644) && @rename($rollback, $path);
                if ($rollback !== false && file_exists($rollback))
                    @unlink($rollback);
            }
            if ($restored)
                exec("systemctl restart dnsmasq 2>&1", $ignored, $rollbackStatus);

            return [
                "ok" => false,
                "error" => $reason . ($restored ? " (rolled back)" : " (ROLLBACK FAILED)"),
            ];
        }
        finally
        {
            if ($tmp !== null && file_exists($tmp))
                @unlink($tmp);
        }
    }
    finally
    {
        flock($lock, LOCK_UN);
        fclose($lock);
    }
}

function firewall_deadlist(string $csvPath = "/etc/persoc/deadlist.csv"): array
{
    if (!is_readable($csvPath))
        return ([
            "ok" => false,
            "error" => "deadlist not readable: " . $csvPath,
            "blocked_v4" => 0,
            "blocked_v6" => 0,
            "entries" => 0,
        ]);

    $raw = file($csvPath, FILE_IGNORE_NEW_LINES);
    if ($raw === false)
        return ([
            "ok" => false,
            "error" => "cannot read deadlist: " . $csvPath,
            "blocked_v4" => 0,
            "blocked_v6" => 0,
            "entries" => 0,
        ]);

    $v4 = [];
    $v6 = [];
    $entries = 0;

    foreach ($raw as $line)
    {
        $line = trim($line);
        if ($line === "" || str_starts_with($line, "#"))
            continue;

        // Parse CSV (first field only)
        $cols = str_getcsv($line);
        if (!$cols || !isset($cols[0]))
            continue;

        $target = trim($cols[0]);
        if ($target === "")
            continue;

        $entries++;

        // If already an IP, store it directly.
        if (filter_var($target, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4))
	{
            $v4[$target] = true;
            continue;
        }
        if (filter_var($target, FILTER_VALIDATE_IP, FILTER_FLAG_IPV6))
	{
            $v6[$target] = true;
            continue;
        }

        // Otherwise, resolve hostname to A/AAAA.
        // A records (IPv4)
        $a = @gethostbynamel($target);
        if (is_array($a))
            foreach ($a as $ip)
                if (filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4))
                    $v4[$ip] = true;

        // AAAA records (IPv6)
        $aaaa = @dns_get_record($target, DNS_AAAA);
        if (is_array($aaaa))
            foreach ($aaaa as $rec)
                if (isset($rec["ipv6"]) && filter_var($rec["ipv6"], FILTER_VALIDATE_IP, FILTER_FLAG_IPV6))
                    $v6[$rec["ipv6"]] = true;
    }
	
    // Convert to flat arrays
    $v4List = array_keys($v4);
    $v6List = array_keys($v6);

    // --- nftables setup (idempotent) ---
    // We assume your firewall_reset already did:
    //   nft flush ruleset; nft add table inet filter
    //
    // Here, we ensure output chain + sets + rules exist and refresh set contents.

    $cmds = [];

    // Ensure table exists (safe if already there; ignore errors with "2>/dev/null || true")
    $cmds[] = "nft add table inet filter 2>/dev/null || true";

    // Ensure output chain exists
    $cmds[] = "nft add chain inet filter output '{ type filter hook output priority 0; policy accept; }' 2>/dev/null || true";

    // Ensure sets exist (one v4, one v6)
    $cmds[] = "nft add set inet filter deadlist_v4 '{ type ipv4_addr; flags interval; }' 2>/dev/null || true";
    $cmds[] = "nft add set inet filter deadlist_v6 '{ type ipv6_addr; flags interval; }' 2>/dev/null || true";

    // Flush set contents (but keep sets)
    $cmds[] = "nft flush set inet filter deadlist_v4 2>/dev/null || true";
    $cmds[] = "nft flush set inet filter deadlist_v6 2>/dev/null || true";

    // Refill sets
    if (count($v4List) > 0)
    {
        $elems = implode(", ", array_map(fn($ip) => $ip, $v4List));
        $cmds[] = "nft add element inet filter deadlist_v4 { " . $elems . " }";
    }
    if (count($v6List) > 0)
    {
        $elems = implode(", ", array_map(fn($ip) => $ip, $v6List));
        $cmds[] = "nft add element inet filter deadlist_v6 { " . $elems . " }";
    }

    // Ensure rules exist (only add if not already present)
    // Rule names are not always available; we check with grep on 'nft list chain'
    // and add if missing.
    $cmds[] =
        "nft list chain inet filter output 2>/dev/null | grep -q 'ip daddr @deadlist_v4 drop' || " .
        "nft add rule inet filter output ip daddr @deadlist_v4 drop"
	;
    $cmds[] =
        "nft list chain inet filter output 2>/dev/null | grep -q 'ip6 daddr @deadlist_v6 drop' || " .
        "nft add rule inet filter output ip6 daddr @deadlist_v6 drop"
	;

    // Execute commands
    $ok = true;
    $errors = [];
    foreach ($cmds as $c)
    {
        // shell-safe execution: command is fixed; only IPs are injected, but they are validated above.
        $ret = 0;
        @system($c, $ret);
        if ($ret !== 0)
	{
            // Many commands are "|| true"; ret here means a real failure.
            // We still record it.
            $ok = false;
            $errors[] = $c;
        }
    }

    $dns = ["ok" => true, "enabled" => false];
    if (function_exists("persoc_dns_enabled") && persoc_dns_enabled())
    {
        $dns = persoc_dns_apply_deadlist($csvPath);
        if (!(($dns["ok"] ?? false) === true))
        {
            $ok = false;
            $errors[] = "DNS guard: " . ($dns["error"] ?? "unknown error");
        }
    }

    return ([
        "ok" => $ok,
        "error" => $ok ? "" : ("nft errors on: " . implode(" | ", $errors)),
        "blocked_v4" => count($v4List),
        "blocked_v6" => count($v6List),
        "entries" => $entries,
        "dns" => $dns,
    ]);
}
